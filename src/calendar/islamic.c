typedef char qjs_cal_umalqura_has_301_years[
    sizeof(umalqura_month_lengths) / sizeof(umalqura_month_lengths[0]) == 301 ? 1 : -1];

static int umalqura_year_length(int32_t year)
{
    uint16_t mask = umalqura_month_lengths[year - 1300];
    int days = 348;
    while (mask) { days += mask & 1; mask >>= 1; }
    return days;
}
static int64_t civil_start(int32_t year)
{
    return 354LL * (year - 1LL) + qjs_cal_floor_div(11LL * year + 3, 30);
}
int64_t qjs_cal_islamic_year_start(QJSCalendarId calendar, int32_t year)
{
    int64_t start;
    int32_t y;
    if (calendar == QJS_CAL_ISLAMIC_UMALQURA && year >= 1300 && year <= 1600) {
        /* Exact cumulative arithmetic avoids ICU's floating regression fit
         * and correction array. Anchor: ICU yearStart(1300) == 460322. */
        start = 460322;
        for (y = 1300; y < year; y++) start += umalqura_year_length(y);
    } else start = civil_start(year);
    return start + INT64_C(1948440) - 2440588 -
           (calendar == QJS_CAL_ISLAMIC_TBLA);
}
int qjs_cal_islamic_month_length(QJSCalendarId calendar, int32_t year,
                                int month)
{
    if (calendar == QJS_CAL_ISLAMIC_UMALQURA && year >= 1300 && year <= 1600)
        return 29 + !!(umalqura_month_lengths[year - 1300] &
                       (1U << (12 - month)));
    return 29 + (month & 1) +
           (month == 12 && civil_start(year + 1) - civil_start(year) == 355);
}
